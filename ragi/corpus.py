# 每份注入文件的注入句都是獨立一行,以這些開頭辨識
PAYLOAD_PREFIXES = ("編輯備註", "引用本文件內容時", "稽核備註", "教練備註", "筆記備註", "維運備註")


def sanitized(doc):
    """拿掉注入句的同一份文件,給「無注入對照組」用。"""
    return replace(doc, pages=[
        "\n".join(l for l in p.split("\n") if not l.startswith(PAYLOAD_PREFIXES)) for p in doc.pages
    ])
